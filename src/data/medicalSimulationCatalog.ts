export function getSimulationScenarioById(scenarioId) {
  return SIMULATION_SCENARIOS.find((scenarioItem) => scenarioItem.id === scenarioId) || null;
}

export function getRecommendedSimulationScenarios(profile: any = {}) {
  const role = String(profile.role || profile.normalizedRole || '').toLowerCase();
  const specialty = String(profile.specialty || '').toLowerCase();
  const workspace = String(profile.workspace || profile.activeWorkspaceId || '').toLowerCase();
  const ids =
    ROLE_RECOMMENDATION_MAP[role] ||
    ROLE_RECOMMENDATION_MAP[specialty] ||
    ROLE_RECOMMENDATION_MAP[workspace] ||
    ROLE_RECOMMENDATION_MAP['medical student'];
  return ids.map(getSimulationScenarioById).filter(Boolean);
}

export function buildScenarioDebrief(scenarioItem, selectedActionIds = [] as any[]) {
  const selected = new Set(selectedActionIds);
  const correctActions = scenarioItem.criticalActions.filter((action) => selected.has(action));
  const missedCriticalActions = scenarioItem.criticalActions.filter((action) => !selected.has(action));
  const safetyScore = Math.max(40, Math.round((correctActions.length / scenarioItem.criticalActions.length) * 100));

  return {
    summary: `${scenarioItem.title} completed in demo mode with ${correctActions.length} of ${scenarioItem.criticalActions.length} critical actions selected.`,
    correctActions,
    missedCriticalActions,
    timeToCriticalActionSeconds: 210 + missedCriticalActions.length * 25,
    safetyRisks: missedCriticalActions.length
      ? ['Delayed recognition/escalation risk', 'Incomplete closed-loop documentation']
      : ['No major demo safety risks flagged'],
    toolUsage: scenarioItem.requiredTools,
    evidenceNotes: [
      'Use calculators and protocols as clinical decision support only.',
      'Escalate deterioration using local policy and clinician judgment.',
    ],
    reflectionPrompts: [
      'What happened?',
      'What went well?',
      'What could improve?',
      'What will you do next time?',
    ],
    aiTutorFeedback:
      safetyScore >= 85
        ? 'Strong prioritization and safety framing. Continue practicing team communication under time pressure.'
        : 'Focus next practice on earlier recognition, tool selection, and closed-loop escalation of critical findings.',
    nextRecommendedScenarios: scenarioItem.nextRecommendedScenarioIds.map(getSimulationScenarioById).filter(Boolean),
    scores: {
      safetyScore,
      communicationScore: Math.max(50, safetyScore - 4),
      teamworkScore: Math.max(50, safetyScore - 6),
      debriefQualityScore: 78,
    },
  };
}

