function page({
  id,
  label,
  path,
  componentKey,
  navId,
  screenshotSlug,
  loadEndpoints = [] as readonly any[],
  actionEndpoints = [] as readonly any[],
  duplicateRenderPaths = [] as readonly any[],
  backendContract = 'real',
  movementStages = [] as readonly any[],
  notes = '',
}) {
  return Object.freeze({
    id,
    label,
    path,
    componentKey,
    navId,
    screenshotSlug,
    loadEndpoints: Object.freeze(loadEndpoints),
    actionEndpoints: Object.freeze(actionEndpoints),
    duplicateRenderPaths: Object.freeze(duplicateRenderPaths),
    backendContract,
    movementStages: Object.freeze(movementStages),
    notes,
  });
}

