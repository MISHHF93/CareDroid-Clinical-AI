export const PLATFORM_SYSTEM_CAPABILITY_IDS = Object.freeze(
  PLATFORM_SYSTEM_CAPABILITIES.map((capability) => capability.id)
);

export const PLATFORM_SYSTEM_CAPABILITY_BY_ID = Object.freeze(
  Object.fromEntries(PLATFORM_SYSTEM_CAPABILITIES.map((capability) => [capability.id, capability]))
);

export function getPlatformSystemCapabilities() {
  return PLATFORM_SYSTEM_CAPABILITIES;
}

export function getPlatformSystemCapabilityById(id) {
  return PLATFORM_SYSTEM_CAPABILITY_BY_ID[id] || null;
}

export function routeTemplateToRegex(route) {
  const escaped = route.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/:patientId/g, '[^/]+');
  return new RegExp(`^${escaped}$`);
}

export function getPlatformSystemCapabilityByPath(pathname) {
  const normalized = pathname || '';
  return (
    PLATFORM_SYSTEM_CAPABILITIES.find((capability) => routeTemplateToRegex(capability.route).test(normalized)) ||
    null
  );
}

export function getPlatformSystemCapabilitiesByPack(pack) {
  return PLATFORM_SYSTEM_CAPABILITIES.filter((capability) => capability.pack === pack);
}

export function getPlatformSystemRoutePaths() {
  return PLATFORM_SYSTEM_CAPABILITIES.map((capability) => capability.route);
}

