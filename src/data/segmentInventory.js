export function getCanonicalSegmentInventory() {
  return SEGMENT_INVENTORY;
}

export function getSegmentInventoryById(records = SEGMENT_INVENTORY) {
  return Object.fromEntries(records.map((record) => [record.id, record]));
}

export function resolveSegmentRecord(id, records = SEGMENT_INVENTORY) {
  if (!id) return null;
  return getSegmentInventoryById(records)[id] || null;
}

export function getFrontendOnlySegments(records = SEGMENT_INVENTORY) {
  return records.filter((record) =>
    [SEGMENT_STATUSES.FRONTEND_ONLY, SEGMENT_STATUSES.STALE_MOCK_ONLY].includes(record.status)
  );
}

export function getBackendOnlySegments(records = SEGMENT_INVENTORY) {
  return records.filter((record) => record.status === SEGMENT_STATUSES.BACKEND_ONLY);
}

export function getSegmentsByNavEntry(navEntry, records = SEGMENT_INVENTORY) {
  return records.filter((record) => record.navEntry === navEntry);
}

export function getSegmentInventorySummary(records = SEGMENT_INVENTORY) {
  return records.reduce(
    (summary, record) => {
      summary.total += 1;
      summary.byStatus[record.status] = (summary.byStatus[record.status] || 0) + 1;
      summary.byArea[record.area] = (summary.byArea[record.area] || 0) + 1;
      if (record.navEntry) summary.navBacked += 1;
      if (record.backendEndpoints.length > 0) summary.backendLinked += 1;
      if (record.bridges.gaps.length > 0) summary.withGaps += 1;
      return summary;
    },
    {
      total: 0,
      navBacked: 0,
      backendLinked: 0,
      withGaps: 0,
      byStatus: {},
      byArea: {},
    }
  );
}
