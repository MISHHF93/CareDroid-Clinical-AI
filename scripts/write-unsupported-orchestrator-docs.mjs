/**
 * Regenerate docs/unsupported-orchestrator-tools.md from contract sources (no Vite imports).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function read(rel) {
  return readFileSync(join(root, rel), 'utf8');
}

function parseStringArray(block) {
  return [...block.matchAll(/'([^']+)'/g)].map((m) => m[1]);
}

function parseNluEnum(source) {
  const block = source.match(/export const NLU = Object\.freeze\(\{([\s\S]*?)\}\);/);
  const map = {};
  for (const m of block[1].matchAll(/(\w+):\s*'([^']+)'/g)) {
    map[m[1]] = m[2];
  }
  return map;
}

function parseRegistryEnum(source) {
  const block = source.match(/export const REGISTRY = Object\.freeze\(\{([\s\S]*?)\}\);/);
  const map = {};
  for (const m of block[1].matchAll(/(\w+):\s*'([^']+)'/g)) {
    map[m[1]] = m[2];
  }
  return map;
}

function parseRegistryToOrchestrator(source, nlu, registry) {
  const block = source.match(/REGISTRY_ID_TO_ORCHESTRATOR_TOOL\s*=\s*Object\.freeze\(\{([\s\S]*?)\}\)/);
  const map = {};
  for (const m of block[1].matchAll(/\[REGISTRY\.(\w+)\]:\s*NLU\.(\w+)/g)) {
    map[registry[m[1]]] = nlu[m[2]];
  }
  for (const m of block[1].matchAll(/'([^']+)':\s*'([^']+)'/g)) {
    map[m[1]] = m[2];
  }
  return map;
}

function parseOrchestratorRegistered(source, nlu) {
  const block = source.match(
    /ORCHESTRATOR_REGISTERED_NLU_TOOL_IDS\s*=\s*Object\.freeze\(\[([\s\S]*?)\]\)/,
  );
  const ids = [];
  for (const m of block[1].matchAll(/NLU\.(\w+)/g)) {
    ids.push(nlu[m[1]]);
  }
  ids.push(...parseStringArray(block[1]));
  return [...new Set(ids)];
}

const contractSource = read('src/data/clinicalToolIdContract.ts');
const registrySource = read(
  'backend/src/modules/medical-control-plane/tool-orchestrator/tool-orchestrator.registry.ts',
);

const nlu = parseNluEnum(contractSource);
const registry = parseRegistryEnum(contractSource);
const frontendRegistered = parseOrchestratorRegistered(contractSource, nlu);
const registryMap = parseRegistryToOrchestrator(contractSource, nlu, registry);

const registered = parseStringArray(
  registrySource.match(/REGISTERED_EXECUTOR_TOOL_IDS\s*=\s*\[([\s\S]*?)\]\s*as const/)[1],
);
const backendUnsupported = parseStringArray(
  registrySource.match(/NLU_TOOL_IDS_WITHOUT_EXECUTOR\s*=\s*\[([\s\S]*?)\]\s*as const/)[1],
);

const lines = [
  '# Unsupported orchestrator tools (NLU without POST executor)',
  '',
  'Generated by `npm run orchestrator:write-docs`.',
  'Do not add fake `registerTool()` handlers for unsupported ids.',
  '',
  `## Registered POST executors (${frontendRegistered.length})`,
  '',
  '| NLU tool id | Registry id | Endpoint |',
  '|-------------|-------------|----------|',
];

for (const nluId of frontendRegistered) {
  const registryId = Object.entries(registryMap).find(([, v]) => v === nluId)?.[0] ?? '—';
  lines.push(`| \`${nluId}\` | \`${registryId}\` | \`POST /api/tools/${nluId}/execute\` |`);
}

lines.push(
  '',
  '## Unsupported NLU profiles',
  '',
  '| NLU id | Notes |',
  '|--------|-------|',
);

for (const id of backendUnsupported.sort()) {
  const note =
    id === 'dispatch-ai'
      ? 'Chat/NLU only — `backendExecutable` for routing, not POST execute'
      : 'Client-side calculator, clinical page, fleet UI, or chat-assisted workflow';
  lines.push(`| \`${id}\` | ${note} |`);
}

lines.push(
  '',
  '## Backend parity',
  '',
  `- \`REGISTERED_EXECUTOR_TOOL_IDS\`: ${registered.join(', ')}`,
  `- \`NLU_TOOL_IDS_WITHOUT_EXECUTOR\`: ${backendUnsupported.length} ids (listed above)`,
  '',
  '## Client behavior',
  '',
  '- `classifyOrchestratorExecution()` → explicit `unsupported` before fetch',
  '- `executeClinicalTool()` in `src/services/clinicalOrchestratorApi.ts`',
  '- `resolveOrchestratorToolForLaunch()` only when `isOrchestratorPostExecutable()`',
  '',
);

const outPath = join(root, 'docs/unsupported-orchestrator-tools.md');
writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8');
console.log(`Wrote ${outPath} (${backendUnsupported.length} unsupported NLU ids)`);
